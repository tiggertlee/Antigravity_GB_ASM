SECTION "GraphicsRoutines", ROM0

; ------------------------------------------------------------------------------
; LoadGraphics - Copies all tile bitmaps to VRAM Pattern Table 0 ($8000)
; NOTE: Must be called when LCD is OFF or during VBlank.
; ------------------------------------------------------------------------------
LoadGraphics::
    ld hl, _VRAM_TILES          ; Destination in VRAM ($8000)
    ld de, GameTiles            ; Source in ROM
    ld bc, TOTAL_TILES * 16     ; Total bytes to copy (48 tiles * 16 bytes = 768 bytes)
.copyLoop:
    ld a, [de]                  ; Read byte from ROM
    ld [hli], a                 ; Write byte to VRAM and increment HL
    inc de                      ; Point to next ROM byte
    dec bc                      ; Decrement 16-bit counter
    ld a, b
    or c                        ; Check if BC == 0
    jr nz, .copyLoop
    ret

